/** Local-image URL scheme understood by getCardImageSource() in components/Card.tsx. */
export const DELTA_REIGN_IMAGE_PREFIX = 'deltareign:';

export function deltaReignImageUrl(imageKey: string): string {
    return DELTA_REIGN_IMAGE_PREFIX + imageKey;
}

/** Resolve a `deltareign:<key>` url to a bundled asset, or undefined if not one. */
export function resolveDeltaReignImage(imageUrl?: string): number | undefined {
    if (!imageUrl || !imageUrl.startsWith(DELTA_REIGN_IMAGE_PREFIX)) return undefined;
    return DELTA_REIGN_IMAGES[imageUrl.slice(DELTA_REIGN_IMAGE_PREFIX.length)];
}

/** Convert a set entry into a playable Card. `index` keeps ids unique per copy. */
export function toCard(entry: DeltaReignCard, index: number = 0): Card {
    const url = deltaReignImageUrl(entry.imageKey);
    return {
        ...entry,
        id: `${DELTA_REIGN_SET_ID}-${entry.number}-${index}`,
        type: entry.type || 'pokemon',
        imageUrl: url,
        imageUrlLarge: url,
    } as Card;
}

export function findDeltaReignCard(name: string): DeltaReignCard | undefined {
    return DELTA_REIGN_CARDS.find(c => c.name.toLowerCase() === name.toLowerCase());
}
